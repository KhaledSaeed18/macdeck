#!/usr/bin/env python3
"""Convert BDF bitmap fonts (printable ASCII 32..126 only) into one C header.

Usage: scripts/bdf2c.py out.h name=path.bdf [name=path.bdf ...]
Each glyph is stored row by row, MSB-first, ceil(width/8) bytes per row.
"""
import sys


def parse(path):
    w = h = None
    glyphs, cur, bitmap, rows = {}, None, False, []
    for line in open(path, encoding="latin-1"):
        p = line.split()
        if not p:
            continue
        if p[0] == "FONTBOUNDINGBOX":
            w, h = int(p[1]), int(p[2])
        elif p[0] == "ENCODING":
            cur = int(p[1])
        elif p[0] == "BITMAP":
            bitmap, rows = True, []
        elif p[0] == "ENDCHAR":
            if cur is not None and 32 <= cur <= 126:
                glyphs[cur] = rows
            bitmap, cur = False, None
        elif bitmap:
            rows.append(bytes.fromhex(p[0]))
    missing = [c for c in range(32, 127) if c not in glyphs]
    assert not missing, f"{path}: missing glyphs {missing}"
    stride = (w + 7) // 8
    for c, rows in glyphs.items():
        assert len(rows) == h and all(len(r) == stride for r in rows), f"{path}: bad glyph {c}"
    return w, h, glyphs


def main():
    out, specs = sys.argv[1], [a.split("=", 1) for a in sys.argv[2:]]
    lines = ["/* Generated by scripts/bdf2c.py — do not edit.",
             " * Glyphs from the Spleen font, Copyright (c) 2018-2026 Frederic Cambus,",
             " * BSD 2-Clause license: see third_party/spleen/LICENSE. */",
             "#pragma once", "#include <stdint.h>",
             "typedef struct { int w, h, stride; const uint8_t *data; } Font;", ""]
    for name, path in specs:
        w, h, glyphs = parse(path)
        stride = (w + 7) // 8
        data = b"".join(b"".join(glyphs[c]) for c in range(32, 127))
        lines.append(f"static const uint8_t {name}_data[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            lines.append("  " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        lines += ["};", f"static const Font {name} = {{ {w}, {h}, {stride}, {name}_data }};", ""]
    open(out, "w").write("\n".join(lines))
    print(f"{out}: {', '.join(n for n, _ in specs)}")


if __name__ == "__main__":
    main()
